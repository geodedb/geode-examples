#!/bin/bash
# compare_canary.sh - Cross-reference claims with CANARY markers
#
# Usage: ./scripts/compare_canary.sh [GEODE_DIR] [DOCS_DIR]
#
# This script:
# 1. Extracts CANARY markers from geode codebase
# 2. Extracts CANARY markers from documentation
# 3. Compares and reports coverage

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"

GEODE_DIR="${1:-${PROJECT_ROOT}/../geode}"
DOCS_DIR="${2:-${PROJECT_ROOT}/../geodedb.com}"
OUTPUT_FILE="${PROJECT_ROOT}/docs/CANARY_CROSSREF.md"

if [ ! -d "$GEODE_DIR" ]; then
    echo "Error: Geode directory not found at $GEODE_DIR"
    exit 1
fi

if [ ! -d "$DOCS_DIR" ]; then
    echo "Error: Documentation directory not found at $DOCS_DIR"
    exit 1
fi

echo "Cross-referencing CANARY markers..."

# Temporary files
GEODE_CANARY=$(mktemp)
DOCS_CANARY=$(mktemp)
trap "rm -f $GEODE_CANARY $DOCS_CANARY" EXIT

# Extract CANARY markers from geode codebase
echo "Extracting from geode codebase..."
grep -roh 'CANARY:.*REQ=[^;]*' "$GEODE_DIR/src" "$GEODE_DIR/tests" 2>/dev/null | \
    grep -oh 'REQ=[^;]*' | \
    sed 's/REQ=//' | \
    sort -u > "$GEODE_CANARY"

geode_count=$(wc -l < "$GEODE_CANARY")
echo "  Found $geode_count unique CANARY markers in geode"

# Extract CANARY markers from documentation
echo "Extracting from documentation..."
grep -roh 'CANARY:.*REQ=[^;]*' "$DOCS_DIR/content" 2>/dev/null | \
    grep -oh 'REQ=[^;]*' | \
    sed 's/REQ=//' | \
    sort -u > "$DOCS_CANARY"

docs_count=$(wc -l < "$DOCS_CANARY")
echo "  Found $docs_count unique CANARY markers in docs"

# Generate cross-reference report
cat > "$OUTPUT_FILE" << EOF
# CANARY Cross-Reference Report

Cross-reference between CANARY markers in geode codebase and geodedb.com documentation.

**Generated:** $(date -Iseconds)

## Summary

| Source | Unique Markers |
|--------|---------------|
| Geode Codebase | $geode_count |
| Documentation | $docs_count |

## Coverage Analysis

### Markers in Both (Verified Claims)

These markers appear in both the codebase and documentation, indicating verified claims.

\`\`\`
EOF

comm -12 "$GEODE_CANARY" "$DOCS_CANARY" >> "$OUTPUT_FILE"
both_count=$(comm -12 "$GEODE_CANARY" "$DOCS_CANARY" | wc -l)

cat >> "$OUTPUT_FILE" << EOF
\`\`\`

**Count:** $both_count

### Markers Only in Codebase

These markers exist in the codebase but are not referenced in documentation.

\`\`\`
EOF

comm -23 "$GEODE_CANARY" "$DOCS_CANARY" | head -50 >> "$OUTPUT_FILE"
code_only=$(comm -23 "$GEODE_CANARY" "$DOCS_CANARY" | wc -l)

cat >> "$OUTPUT_FILE" << EOF
\`\`\`

**Count:** $code_only (showing first 50)

### Markers Only in Documentation

These markers are referenced in documentation but not found in codebase.
This may indicate outdated documentation or missing implementation.

\`\`\`
EOF

comm -13 "$GEODE_CANARY" "$DOCS_CANARY" >> "$OUTPUT_FILE"
docs_only=$(comm -13 "$GEODE_CANARY" "$DOCS_CANARY" | wc -l)

cat >> "$OUTPUT_FILE" << EOF
\`\`\`

**Count:** $docs_only

## Statistics

| Metric | Value |
|--------|-------|
| Total Unique Markers | $((geode_count + docs_only)) |
| Verified (in both) | $both_count |
| Code-only | $code_only |
| Docs-only | $docs_only |
| Coverage Rate | $(echo "scale=1; $both_count * 100 / ($both_count + $docs_only)" | bc)% |

---

## Recommendations

EOF

if [ $docs_only -gt 0 ]; then
    cat >> "$OUTPUT_FILE" << EOF
1. **Documentation markers without code ($docs_only)**: Review these markers and either:
   - Implement the missing functionality in geode
   - Remove outdated documentation claims

EOF
fi

if [ $code_only -gt 50 ]; then
    cat >> "$OUTPUT_FILE" << EOF
2. **Code markers not in docs ($code_only)**: Consider documenting these implemented features
   to improve documentation coverage.

EOF
fi

cat >> "$OUTPUT_FILE" << EOF

---

*Generated by \`scripts/compare_canary.sh\`*
EOF

echo ""
echo "Cross-reference report generated: $OUTPUT_FILE"
echo ""
echo "Summary:"
echo "  - Markers in both: $both_count"
echo "  - Code-only: $code_only"
echo "  - Docs-only: $docs_only"
